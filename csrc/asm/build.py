#!/usr/bin/env python3
"""Generates the FP8 attention kernels (d128.py, d192.py), assembles them for gfx950 with ROCm clang and ld.lld, and
writes C headers embedding the code objects, which the launchers load with hipModuleLoadData.

Usage: python build.py --out-dir DIR [--rocm PATH]"""
import argparse
import os
import pathlib
import subprocess
import sys

sys.dont_write_bytecode = True   # keep the source tree free of __pycache__
import d128  # noqa: E402
import d192  # noqa: E402

KERNELS = [(d128, "fmha_fp8_d128_pp", "kFmhaFp8D128PP"),
           (d192, "fmha_fp8_d192_pp", "kFmhaFp8D192PP")]


def build(gen, stem, sym, out, llvm):
    text, pads = gen.generate()
    s = out / f"{stem}.s"
    s.write_text(text)
    obj, co = out / f"{stem}.o", out / f"{stem}.co"
    subprocess.run([str(llvm / "clang"), "-x", "assembler", "-target", "amdgcn-amd-amdhsa", "-mcpu=gfx950", "-c",
                    str(s), "-o", str(obj)], check=True)
    subprocess.run([str(llvm / "ld.lld"), "-shared", str(obj), "-o", str(co)], check=True)
    data = co.read_bytes()
    lines = [f"// generated by csrc/asm/build.py from {gen.__name__}.py; do not edit",
             "#pragma once", "#include <cstddef>",
             f"static const unsigned char {sym}[{len(data)}] __attribute__((aligned(16))) = {{"]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines += ["};", f"static const size_t {sym}Size = {len(data)};", ""]
    header = out / f"{stem}_co.h"
    header.write_text("\n".join(lines))
    print(f"[build] {s} ({len(pads)} hazard paddings) -> {co} ({len(data)} B) -> {header}", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--rocm", default=os.environ.get("ROCM_PATH", "/opt/rocm"))
    a = ap.parse_args()
    out = pathlib.Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    llvm = pathlib.Path(a.rocm) / "llvm" / "bin"
    for gen, stem, sym in KERNELS:
        build(gen, stem, sym, out, llvm)


if __name__ == "__main__":
    main()
